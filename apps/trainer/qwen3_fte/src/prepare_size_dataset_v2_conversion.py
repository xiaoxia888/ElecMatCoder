def normalize_schedule_token(token: str) -> str:
    compact = re.sub(r"[\s.\-]", "", token.upper())
    if compact.endswith("XXS") or compact == "XXS":
        return "XXS"
    if compact.endswith("XS") or compact == "XS":
        return "XS"
    if compact.endswith("STD") or compact == "STD":
        return "STD"
    match = re.search(r"(\d+)(S?)$", compact)
    return f"SCH{match.group(1)}{match.group(2)}" if match else ""


