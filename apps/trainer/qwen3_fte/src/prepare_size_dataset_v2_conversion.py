def load_type_lookup(type_dir: Path) -> tuple[dict[str, str], set[str]]:
    lookup: dict[str, str] = {}
    conflicts: set[str] = set()
    for name in TYPE_FILES:
        path = type_dir / name
        if not path.exists():
            continue
        for row in load_json_array(path):
            key = canonical_input(row.get("input"))
            output = row.get("output") if isinstance(row.get("output"), dict) else {}
            type_value = output.get("TYPE") if isinstance(output.get("TYPE"), dict) else {}
            body = str(type_value.get("BODY") or "").strip()
            if not key or not body:
                continue
            if key in lookup and lookup[key] != body:
                conflicts.add(key)
                lookup.pop(key, None)
                continue
            if key not in conflicts:
                lookup[key] = body
    return lookup, conflicts


def topology_from_text(text: str, known_body: str = "") -> tuple[str, list[str]]:
    evidence_text = f"{known_body} {text}"
    evidence: list[str] = []
    if JACKET_PATTERN.search(evidence_text):
        evidence.append("JACKET")
    if LINING_PATTERN.search(evidence_text):
        evidence.append("LINING")
    if BRANCH_PATTERN.search(evidence_text):
        evidence.append("BRANCH")
    if REDUCER_PATTERN.search(evidence_text):
        evidence.append("REDUCER")

    if "JACKET" in evidence or "LINING" in evidence:
        return "COMPLEX_SCOPE", evidence
    if "BRANCH" in evidence:
        return "BRANCH", evidence
    if "REDUCER" in evidence:
        return "REDUCER", evidence
    return "SINGLE", evidence


def assignment(
    source_index: int,
    scope: str,
    role: str,
    *,
    explicit_repeat: bool = False,
) -> dict[str, Any]:
    result = {"source_index": source_index, "SCOPE": scope, "ROLE": role}
    if explicit_repeat:
        result["explicit_repeat"] = True
    return result


def canonical_number(value: str) -> Fraction | None:
    text = unicodedata.normalize("NFKC", str(value or "")).strip()
    mixed = re.fullmatch(r"(\d+)\s*[- ]\s*(\d+)/(\d+)", text)
    if mixed:
        return Fraction(int(mixed.group(1)), 1) + Fraction(int(mixed.group(2)), int(mixed.group(3)))
    fraction = re.fullmatch(r"(\d+)/(\d+)", text)
    if fraction:
        return Fraction(int(fraction.group(1)), int(fraction.group(2)))
    try:
        return Fraction(text)
    except (ValueError, ZeroDivisionError):
        return None


def exact_number_text(value: str) -> str:
    return re.sub(r"\s+", "", unicodedata.normalize("NFKC", str(value or "")).upper()).replace("-", " ")


def normalized_mapping_text(value: str) -> str:
    text = unicodedata.normalize("NFKC", value).upper()
    text = re.sub(r"(?<=\d)\.\s+(?=\d)", ".", text)
    text = re.sub(r"(?<=\.)[OＯ](?=\s*MM)", "0", text)
    text = re.sub(r"(?<=\d)\s*M\s+M(?=[^A-Z]|$)", "MM", text)
    # OCR frequently emits xL5/xI5 for x15 in an otherwise numeric size pair.
    text = re.sub(r"(?<=[X×*])\s*[LI](?=\d)", "1", text)
    text = re.sub(r"(?<=DN)[IO](?=\d)", lambda match: "1" if match.group() == "I" else "0", text)
    text = re.sub(r"(?<=DN\d)[O](?=\s*[X×*])", "0", text)
    # Numbered clauses are frequently glued to the preceding value: DN80X252.规格.
    text = re.sub(r"(?<=\d)([234])\.(?=(?:型号|规格|焊接|连接|充氩))", r" \1.", text)
    # A material grade 20 can be glued to a decimal wall immediately before DN.
    text = re.sub(r"(\d+\.\d{1,2})20(?=\s*DN)", r"\1 20", text)
    text = re.sub(
        r"(SCH(?:EDULE)?\s*\.?\s*-?\s*\d+\s*S)(?=\d+\s*[.、．])",
        r"\1 ",
        text,
    )
    return text


def find_item_index(items: list[dict[str, str]], item_type: str, raw_value: str) -> int | None:
    candidates = [index for index, item in enumerate(items) if item["type"] == item_type]
    exact = [
        index
        for index in candidates
        if exact_number_text(items[index]["value"]) == exact_number_text(raw_value)
    ]
    if len(exact) == 1:
        return exact[0]

    number = canonical_number(raw_value)
    equivalent = [
        index
        for index in candidates
        if number is not None and canonical_number(items[index]["value"]) == number
    ]
    return equivalent[0] if len(equivalent) == 1 else None


def matching_item_indexes(
    items: list[dict[str, str]], item_type: str, raw_value: str
) -> list[int]:
    expected_text = exact_number_text(raw_value)
    exact = [
        index
        for index, item in enumerate(items)
        if item["type"] == item_type
        and exact_number_text(item["value"]) == expected_text
    ]
    if exact:
        return exact
    expected_number = canonical_number(raw_value)
    return [
        index
        for index, item in enumerate(items)
        if item["type"] == item_type
        and expected_number is not None
        and canonical_number(item["value"]) == expected_number
    ]


def find_item_pair(
    items: list[dict[str, str]],
    left_type: str,
    left_value: str,
    right_type: str,
    right_value: str,
) -> tuple[int | None, int | None]:
    same_value = (
        exact_number_text(left_value) == exact_number_text(right_value)
        or (
            canonical_number(left_value) is not None
            and canonical_number(left_value) == canonical_number(right_value)
        )
    )
    if left_type == right_type and same_value:
        matches = matching_item_indexes(items, left_type, left_value)
        if len(matches) >= 2:
            return matches[0], matches[1]
        if len(matches) == 1:
            return matches[0], matches[0]
        return None, None
    return (
        find_item_index(items, left_type, left_value),
        find_item_index(items, right_type, right_value),
    )


def regex_number(value: str) -> str:
    """Build an exact numeric regex from a trusted old-label value."""
    normalized = exact_number_text(value).replace(" ", "")
    if re.fullmatch(r"\d+", normalized):
        return rf"{re.escape(normalized)}(?:\.0+)?"
    return re.escape(normalized)


def item_driven_size_pair_mappings(
    text: str,
    items: list[dict[str, str]],
    left_role: str,
    right_role: str,
) -> list[dict[str, Any]]:
    """Recover damaged separators only when the old labels prove both values."""
    normalized = normalized_mapping_text(text)
    compact = re.sub(r"\s+", "", normalized)
    mappings: list[dict[str, Any]] = []
    for left_index, left in enumerate(items):
        for right_index, right in enumerate(items):
            if left["type"] != right["type"]:
                continue
            if left["value"] == right["value"] and left_index > right_index:
                continue
            left_value = regex_number(left["value"])
            right_value = regex_number(right["value"])
            patterns: list[str] = []
            if left["type"] == "DN":
                patterns.extend(
                    [
                        rf"DN{left_value}[X×*](?:DN)?{right_value}",
                        rf"DN{left_value}DN{right_value}",
                        rf"(?:CL|CLASS)\d{{3,4}}{left_value}[X×*]{right_value}",
                    ]
                )
            elif left["type"] == "OD":
                patterns.append(
                    rf"(?:OD|[ΦφØФф])?{left_value}[X×*]"
                    rf"(?:OD|[ΦφØФф])?{right_value}(?=[X×*/\-]|\b)"
                )
            elif left["type"] == "INCH":
                patterns.append(
                    rf"{left_value}(?:\"|'')?[X×*]{right_value}(?:\"|'')"
                )
            if any(re.search(pattern, compact, re.IGNORECASE) for pattern in patterns):
                mappings.extend(
                    [
                        assignment(left_index, "BODY", left_role),
                        assignment(right_index, "BODY", right_role),
                    ]
                )
    return deduplicate_mappings(mappings)


def item_driven_thickness_pair_mappings(
    text: str,
    size_items: list[dict[str, str]],
    items: list[dict[str, str]],
    left_role: str,
    right_role: str,
) -> list[dict[str, Any]]:
    """Parse glued wall pairs only when an explicit, labeled size pair precedes them."""
    normalized = normalized_mapping_text(text)
    compact = re.sub(r"\s+", "", normalized)
    mappings: list[dict[str, Any]] = []
    size_pairs: list[str] = []
    for left_index, left in enumerate(size_items):
        for right_index, right in enumerate(size_items):
            if left["type"] != right["type"]:
                continue
            if left["value"] == right["value"] and left_index > right_index:
                continue
            left_value = regex_number(left["value"])
            right_value = regex_number(right["value"])
            if left["type"] == "DN":
                size_pairs.extend(
                    [
                        rf"DN{left_value}[X×*](?:DN)?{right_value}",
                        rf"DN{left_value}DN{right_value}",
                    ]
                )
            elif left["type"] == "OD":
                size_pairs.append(
                    rf"(?:OD|[ΦφØФф])?{left_value}[X×*]"
                    rf"(?:OD|[ΦφØФф])?{right_value}"
                )

    for left_index, left in enumerate(items):
        for right_index, right in enumerate(items):
            if left["type"] != right["type"]:
                continue
            if left["value"] == right["value"] and left_index > right_index:
                continue
            left_value = regex_number(left["value"])
            right_value = regex_number(right["value"])
            if left["type"] == "MM":
                wall_pair = (
                    rf"(?:[X×*])?{left_value}(?:MM|毫米)?"
                    rf"[X×*/]{right_value}(?:MM|毫米)?"
                )
            elif left["type"] == "SCHEDULE":
                left_value = re.escape(left["value"].upper().replace("SCH", ""))
                right_value = re.escape(right["value"].upper().replace("SCH", ""))
                wall_pair = (
                    rf"(?:SCH|S)?{left_value}[X×*/]"
                    rf"(?:SCH|S)?{right_value}(?=DN|[^A-Z0-9]|$)"
                )
            else:
                continue
            if any(
                re.search(size_pair + rf".{{0,24}}?" + wall_pair, compact, re.IGNORECASE)
                for size_pair in size_pairs
            ):
                mappings.extend(
                    [
                        assignment(left_index, "BODY", left_role),
                        assignment(right_index, "BODY", right_role),
                    ]
                )
    return deduplicate_mappings(mappings)


def size_item_has_explicit_evidence(text: str, item: dict[str, str]) -> bool:
    pattern_by_type = {
        "DN": EXPLICIT_DN_PATTERN,
        "OD": EXPLICIT_OD_PATTERN,
        "INCH": EXPLICIT_INCH_PATTERN,
    }
    pattern = pattern_by_type.get(item["type"])
    if pattern is None:
        return False
    expected = canonical_number(item["value"])
    return any(
        expected is not None and canonical_number(match.group("value")) == expected
        for match in pattern.finditer(unicodedata.normalize("NFKC", text).upper())
    )


def size_term_type(prefix: str, unit: str) -> str:
    prefix = prefix.upper()
    unit = unit.upper()
    if prefix in {"DN", "D"}:
        return "DN"
    if prefix in {"OD", "Φ", "Ø", "Ф"}:
        return "OD"
    if prefix == "NPS" or unit:
        return "INCH"
    return ""


def mark_explicit_repeats(mappings: list[dict[str, Any]]) -> list[dict[str, Any]]:
    counts = Counter(mapping["source_index"] for mapping in mappings)
    result: list[dict[str, Any]] = []
    for mapping in mappings:
        result.append(
            assignment(
                mapping["source_index"],
                mapping["SCOPE"],
                mapping["ROLE"],
                explicit_repeat=counts[mapping["source_index"]] > 1,
            )
        )
    return result


def deduplicate_mappings(mappings: list[dict[str, Any]]) -> list[dict[str, Any]]:
    unique: dict[tuple[int, str, str], dict[str, Any]] = {}
    for mapping in mappings:
        key = (mapping["source_index"], mapping["SCOPE"], mapping["ROLE"])
        unique[key] = mapping
    return mark_explicit_repeats(list(unique.values()))


def size_pair_mappings(
    text: str,
    items: list[dict[str, str]],
    left_role: str,
    right_role: str,
) -> list[dict[str, Any]]:
    mappings: list[dict[str, Any]] = []
    normalized = normalized_mapping_text(text)
    for match in SIZE_PAIR_PATTERN.finditer(normalized):
        left_prefix = match.group("left_prefix") or ""
        right_prefix = match.group("right_prefix") or ""
        left_unit = match.group("left_unit") or ""
        right_unit = match.group("right_unit") or ""
        left_type = size_term_type(left_prefix, left_unit)
        right_type = size_term_type(right_prefix, right_unit)
        if not left_type and right_type:
            left_type = right_type
        if not right_type and left_type:
            right_type = left_type
        if not left_type and not right_type:
            left_type = right_type = "DN"
        if not left_type or not right_type:
            continue
        left_index, right_index = find_item_pair(
            items,
            left_type,
            match.group("left_value"),
            right_type,
            match.group("right_value"),
        )
        if left_index is None or right_index is None:
            continue
        mappings.extend(
            [
                assignment(left_index, "BODY", left_role),
                assignment(right_index, "BODY", right_role),
            ]
        )
    for match in PREFIXED_HYPHEN_SIZE_PAIR_PATTERN.finditer(normalized):
        left_type = size_term_type(match.group("left_prefix"), "")
        right_type = size_term_type(match.group("right_prefix") or match.group("left_prefix"), "")
        left_index, right_index = find_item_pair(
            items,
            left_type,
            match.group("left_value"),
            right_type,
            match.group("right_value"),
        )
        if left_index is None or right_index is None:
            continue
        mappings.extend(
            [
                assignment(left_index, "BODY", left_role),
                assignment(right_index, "BODY", right_role),
            ]
        )
    for pattern in (GLUED_DN_PAIR_PATTERN, PRODUCT_DN_PAIR_PATTERN):
        for match in pattern.finditer(normalized):
            left_index, right_index = find_item_pair(
                items, "DN", match.group("left"), "DN", match.group("right")
            )
            if left_index is None or right_index is None:
                continue
            mappings.extend(
                [
                    assignment(left_index, "BODY", left_role),
                    assignment(right_index, "BODY", right_role),
                ]
            )
    for match in SIZE_WORD_INCH_PAIR_PATTERN.finditer(normalized):
        left_index, right_index = find_item_pair(
            items, "INCH", match.group("left"), "INCH", match.group("right")
        )
        if left_index is None or right_index is None:
            continue
        mappings.extend(
            [
                assignment(left_index, "BODY", left_role),
                assignment(right_index, "BODY", right_role),
            ]
        )
    for match in MM_GLUE_DN_PAIR_PATTERN.finditer(normalized):
        left_index, right_index = find_item_pair(
            items, "DN", match.group("left"), "DN", match.group("right")
        )
        if left_index is None or right_index is None:
            continue
        mappings.extend(
            [
                assignment(left_index, "BODY", left_role),
                assignment(right_index, "BODY", right_role),
            ]
        )
    return deduplicate_mappings(
        mappings
        + item_driven_size_pair_mappings(text, items, left_role, right_role)
    )


